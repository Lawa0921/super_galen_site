"""NumPy-only, metre-toleranced contact gate for topologically incident faces.

The intersection of convex triangles is generated by contained vertices and
edge intersections. Every intersection extremum must remain inside the shared
vertex/edge simplex (within tolerance). Near-plane pairs are projected only
when BOTH triangles lie within tolerance of the other's plane. Degenerate
incident faces are rejected conservatively, rather than certified as safe.
Noncoplanar faces use inclusive edge/triangle, edge/edge and vertex/face
witnesses, including the clipped endpoints of an edge lying in a face plane.
"""
from functools import lru_cache

import numpy as np

CONTACT_TOLERANCE_M = 1e-7


def _cross(a, b):
    return float(a[0]*b[1] - a[1]*b[0])


def _segment_distance(p, a, b):
    edge = b-a
    squared = float(edge @ edge)
    if squared == 0:
        return float(np.linalg.norm(p-a))
    t = np.clip(float((p-a) @ edge)/squared, 0., 1.)
    return float(np.linalg.norm(p-(a+t*edge)))


def _inside(p, triangle, tolerance):
    orientation = np.sign(_cross(triangle[1]-triangle[0], triangle[2]-triangle[0]))
    return all(orientation*_cross(b-a, p-a) >= -tolerance*np.linalg.norm(b-a)
               for a, b in zip(triangle, np.roll(triangle, -1, axis=0)))


def _intersection_extrema(a, b, tolerance):
    result = [p for p in a if _inside(p, b, tolerance)]
    result.extend(p for p in b if _inside(p, a, tolerance))
    for p, q in zip(a, np.roll(a, -1, axis=0)):
        for r, s in zip(b, np.roll(b, -1, axis=0)):
            u, v = q-p, s-r
            denominator = _cross(u, v)
            # Roundoff threshold, not a geometric/angular coplanarity shortcut.
            roundoff = 8*np.finfo(float).eps*np.linalg.norm(u)*np.linalg.norm(v)
            if abs(denominator) > roundoff:
                t, w = _cross(r-p, v)/denominator, _cross(r-p, u)/denominator
                if 0. <= t <= 1. and 0. <= w <= 1.:
                    result.append(p+t*u)
            # Collinear overlap endpoints, including tolerance-close contacts.
            for point, start, end in ((p, r, s), (q, r, s), (r, p, q), (s, p, q)):
                if _segment_distance(point, start, end) <= tolerance:
                    result.append(point)
    return result


def _closest_segment_point(p, a, b):
    edge = b-a
    return a+np.clip(float((p-a) @ edge)/float(edge @ edge), 0., 1.)*edge


def _closest_triangle_point(p, triangle, normal):
    projection = p-float((p-triangle[0]) @ normal)*normal
    edges = list(zip(triangle, np.roll(triangle, -1, axis=0)))
    if all(float(np.cross(b-a, projection-a) @ normal) >= 0. for a, b in edges):
        return projection
    candidates = [_closest_segment_point(p, a, b) for a, b in edges]
    return min(candidates, key=lambda q: float((p-q) @ (p-q)))


def _closest_edge_points(p, q, r, s):
    u, v, w = q-p, s-r, p-r
    a, b, c, e, f = float(u @ u), float(u @ v), float(u @ w), float(v @ v), float(v @ w)
    denominator = a*e-b*b
    t = np.clip((b*f-c*e)/denominator, 0., 1.) if denominator > 8*np.finfo(float).eps*a*e else 0.
    z = (b*t+f)/e
    if z < 0.:
        z, t = 0., np.clip(-c/a, 0., 1.)
    elif z > 1.:
        z, t = 1., np.clip((b-c)/a, 0., 1.)
    return p+t*u, r+z*v


def _edge_triangle_witnesses(p, q, triangle, normal, tolerance):
    d0, d1 = float((p-triangle[0]) @ normal), float((q-triangle[0]) @ normal)
    if abs(d0) <= tolerance and abs(d1) <= tolerance:
        # Clip the projected edge to the actual face, retaining the complete
        # interval endpoints; a single closest pair would hide foldover length.
        pp, qq = p-d0*normal, q-d1*normal
        low, high = 0., 1.
        for a, b in zip(triangle, np.roll(triangle, -1, axis=0)):
            first = float(np.cross(b-a, pp-a) @ normal)
            last = float(np.cross(b-a, qq-a) @ normal)
            if first < 0. and last < 0.:
                return []
            if first < 0.:
                low = max(low, first/(first-last))
            elif last < 0.:
                high = min(high, first/(first-last))
        if low > high:
            return []
        return [p+low*(q-p), p+high*(q-p), pp+low*(qq-pp), pp+high*(qq-pp)]
    if d0*d1 <= 0.:
        t = d0/(d0-d1)
        point = p+t*(q-p)
        closest = _closest_triangle_point(point, triangle, normal)
        if np.linalg.norm(point-closest) <= tolerance:
            return [point, closest]
    return []


def _noncoplanar_witnesses(a, b, na, nb, tolerance):
    for triangle, other, normal in ((a, b, nb), (b, a, na)):
        for point in triangle:
            closest = _closest_triangle_point(point, other, normal)
            if np.linalg.norm(point-closest) <= tolerance:
                yield point
                yield closest
        for p, q in zip(triangle, np.roll(triangle, -1, axis=0)):
            yield from _edge_triangle_witnesses(p, q, other, normal, tolerance)
    for p, q in zip(a, np.roll(a, -1, axis=0)):
        for r, s in zip(b, np.roll(b, -1, axis=0)):
            first, second = _closest_edge_points(p, q, r, s)
            if np.linalg.norm(first-second) <= tolerance:
                yield first
                yield second


def incident_disallowed_contact(points, face_a, face_b, tolerance=CONTACT_TOLERANCE_M):
    """True means contact beyond shared simplex or incident degeneracy.

    Nonincident pairs remain the existing inclusive gate's responsibility.
    Topological IDs, not coincident coordinates, define what
    contact is allowed. Distances <= tolerance from that simplex are accepted.
    """
    points = np.asarray(points, dtype=float)
    fa, fb = np.asarray(face_a, dtype=int), np.asarray(face_b, dtype=int)
    if points.ndim != 2 or points.shape[1] != 3 or fa.shape != (3,) or fb.shape != (3,):
        raise ValueError('Expected 3D points and two triangular faces')
    if not np.isfinite(tolerance) or tolerance <= 0 or np.any(fa < 0) or np.any(fb < 0):
        raise ValueError('Positive finite tolerance and valid vertex indices required')
    a, b = points[fa], points[fb]
    if not np.all(np.isfinite(a)) or not np.all(np.isfinite(b)):
        raise ValueError('Finite triangle coordinates required')
    shared = sorted(set(fa) & set(fb))
    if not shared:
        return False
    if len(set(fa)) != 3 or len(set(fb)) != 3 or len(shared) == 3:
        return True
    # Translate to the shared point before predicates to limit cancellation.
    origin = points[shared[0]]
    a, b = a-origin, b-origin
    na, nb = np.cross(a[1]-a[0], a[2]-a[0]), np.cross(b[1]-b[0], b[2]-b[0])
    la, lb = np.linalg.norm(na), np.linalg.norm(nb)
    longest_a = max(np.linalg.norm(a[(i+1) % 3]-a[i]) for i in range(3))
    longest_b = max(np.linalg.norm(b[(i+1) % 3]-b[i]) for i in range(3))
    if la <= tolerance*longest_a or lb <= tolerance*longest_b:
        return True  # altitude at/below tolerance cannot certify a face
    na, nb = na/la, nb/lb
    allowed3 = points[shared]-origin
    if max(np.abs((b-a[0]) @ na)) > tolerance or max(np.abs((a-b[0]) @ nb)) > tolerance:
        for point in _noncoplanar_witnesses(a, b, na, nb, tolerance):
            distance = (np.linalg.norm(point-allowed3[0]) if len(shared) == 1
                        else _segment_distance(point, allowed3[0], allowed3[1]))
            if distance > tolerance:
                return True
        return False
    # Orthonormal projection retains metre distances (axis dropping would not).
    u = a[1]-a[0]
    u = u/np.linalg.norm(u)
    basis = np.column_stack((u, np.cross(na, u)))
    pa, pb = a @ basis, b @ basis
    allowed = (points[shared]-origin) @ basis
    for point in _intersection_extrema(pa, pb, tolerance):
        distance = (np.linalg.norm(point-allowed[0]) if len(shared) == 1
                    else _segment_distance(point, allowed[0], allowed[1]))
        if distance > tolerance:
            return True
    return False


@lru_cache(maxsize=32)
def _topology_pairs(face_bytes):
    faces = np.frombuffer(face_bytes, dtype=np.int64).reshape((-1, 3))
    pairs, vertex_faces = set(), {}
    for face_id, face in enumerate(faces):
        for vertex in set(face):
            previous = vertex_faces.setdefault(int(vertex), [])
            pairs.update((other, face_id) for other in previous)
            previous.append(face_id)
    result = np.asarray(sorted(pairs), dtype=np.int64).reshape((-1, 2))
    result.setflags(write=False)
    return result


def incident_pair_indices(faces):
    """Immutable topology-only cache; changing points never changes these pairs."""
    faces = np.asarray(faces, dtype=np.int64)
    if faces.ndim != 2 or faces.shape[1] != 3:
        raise ValueError('Expected triangular faces')
    return _topology_pairs(faces.tobytes())


def _batch_outside(points, allowed0, allowed1, counts, tolerance):
    relative = points-allowed0[:, None, :]
    edge = allowed1-allowed0
    squared = np.sum(edge*edge, axis=1)
    t = np.divide(np.sum(relative*edge[:, None, :], axis=2), squared[:, None],
                  out=np.zeros(relative.shape[:2]), where=squared[:, None] != 0.)
    delta = relative-np.clip(t, 0., 1.)[:, :, None]*edge[:, None, :]
    delta = np.where((counts == 1)[:, None, None], relative, delta)
    return np.linalg.norm(delta, axis=2) > tolerance


def _batch_closest_triangle(points, triangles, normals):
    delta = points-triangles[:, None, 0, :]
    projection = points-np.sum(delta*normals[:, None, :], axis=2)[:, :, None]*normals[:, None, :]
    starts = triangles[:, None, :, :]
    edges = (np.roll(triangles, -1, axis=1)-triangles)[:, None, :, :]
    inside = np.all(np.sum(np.cross(edges, projection[:, :, None, :]-starts)*normals[:, None, None, :], axis=3) >= 0., axis=2)
    t = np.sum((points[:, :, None, :]-starts)*edges, axis=3)/np.sum(edges*edges, axis=3)
    candidates = starts+np.clip(t, 0., 1.)[:, :, :, None]*edges
    squared = np.sum((points[:, :, None, :]-candidates)**2, axis=3)
    choice = np.argmin(squared, axis=2)
    closest = np.take_along_axis(candidates, choice[:, :, None, None], axis=2)[:, :, 0, :]
    return np.where(inside[:, :, None], projection, closest)


def _batch_noncoplanar(a, b, na, nb, allowed0, allowed1, counts, tolerance):
    """Batch the SAME reference witnesses, without plane-separation shortcuts."""
    result = np.zeros(len(a), dtype=bool)
    outside = lambda p: _batch_outside(p, allowed0, allowed1, counts, tolerance)
    for triangle, other, normal in ((a, b, nb), (b, a, na)):
        closest = _batch_closest_triangle(triangle, other, normal)
        contacts = np.linalg.norm(triangle-closest, axis=2) <= tolerance
        result |= np.any(contacts & (outside(triangle) | outside(closest)), axis=1)

        p, q = triangle, np.roll(triangle, -1, axis=1)
        d0 = np.sum((p-other[:, None, 0, :])*normal[:, None, :], axis=2)
        d1 = np.sum((q-other[:, None, 0, :])*normal[:, None, :], axis=2)
        in_plane = (np.abs(d0) <= tolerance) & (np.abs(d1) <= tolerance)
        crosses = (d0*d1 <= 0.) & ~in_plane
        t = np.divide(d0, d0-d1, out=np.zeros_like(d0), where=crosses)
        hits = p+t[:, :, None]*(q-p)
        closest = _batch_closest_triangle(hits, other, normal)
        contacts = crosses & (np.linalg.norm(hits-closest, axis=2) <= tolerance)
        result |= np.any(contacts & (outside(hits) | outside(closest)), axis=1)

        # Edge-in-plane clipping remains the scalar reference, including both
        # interval ends and both source/projection positions. Identical shared
        # edges may be skipped: their entire segment IS the allowed simplex,
        # not a geometric separation claim. Every other clip is evaluated.
        for row, edge_id in np.argwhere(in_plane):
            endpoints = triangle[row, [edge_id, (edge_id+1) % 3]]
            if counts[row] == 2 and all(any(np.array_equal(point, allowed) for allowed in (allowed0[row], allowed1[row])) for point in endpoints):
                continue
            witnesses = _edge_triangle_witnesses(*endpoints, other[row], normal[row], tolerance)
            if witnesses:
                result[row] |= bool(np.any(_batch_outside(np.asarray(witnesses)[None, :, :], allowed0[row:row+1], allowed1[row:row+1], counts[row:row+1], tolerance)))

    p, q = a[:, :, None, :], np.roll(a, -1, axis=1)[:, :, None, :]
    r, s = b[:, None, :, :], np.roll(b, -1, axis=1)[:, None, :, :]
    u, v, w = q-p, s-r, p-r
    aa, bb, cc = np.sum(u*u, axis=3), np.sum(u*v, axis=3), np.sum(u*w, axis=3)
    ee, ff = np.sum(v*v, axis=3), np.sum(v*w, axis=3)
    denominator = aa*ee-bb*bb
    t = np.clip(np.divide(bb*ff-cc*ee, denominator, out=np.zeros_like(denominator),
                          where=denominator > 8*np.finfo(float).eps*aa*ee), 0., 1.)
    z = (bb*t+ff)/ee
    t = np.where(z < 0., np.clip(-cc/aa, 0., 1.), np.where(z > 1., np.clip((bb-cc)/aa, 0., 1.), t))
    z = np.clip(z, 0., 1.)
    first, second = p+t[:, :, :, None]*u, r+z[:, :, :, None]*v
    contacts = np.linalg.norm(first-second, axis=3).reshape((-1, 9)) <= tolerance
    result |= np.any(contacts & (outside(first.reshape((-1, 9, 3))) | outside(second.reshape((-1, 9, 3)))), axis=1)
    return result


def incident_disallowed_pair_mask(points, faces, pairs, tolerance=CONTACT_TOLERANCE_M):
    """Per-pair reference-equivalent mask; noncoplanar feature math is batched.

    Degenerate/duplicate and near-plane decisions retain the scalar contract;
    sparse near-plane intersections use the reference implementation. No
    tolerance, feature set, or allowed-simplex rule changes with batching.
    """
    points, faces, pairs = np.asarray(points, float), np.asarray(faces, np.int64), np.asarray(pairs, np.int64)
    if points.ndim != 2 or points.shape[1] != 3 or faces.ndim != 2 or faces.shape[1] != 3 or pairs.ndim != 2 or pairs.shape[1] != 2:
        raise ValueError('Expected points, triangular faces and face-index pairs')
    if not np.isfinite(tolerance) or tolerance <= 0 or np.any(faces < 0) or np.any(pairs < 0):
        raise ValueError('Positive finite tolerance and valid indices required')
    result = np.zeros(len(pairs), dtype=bool)
    if not len(pairs):
        return result
    fa, fb = faces[pairs[:, 0]], faces[pairs[:, 1]]
    a, b = points[fa], points[fb]
    if not np.all(np.isfinite(a)) or not np.all(np.isfinite(b)):
        raise ValueError('Finite triangle coordinates required')
    shared = np.any(fa[:, :, None] == fb[:, None, :], axis=2)
    counts = shared.sum(axis=1)
    unique = (fa[:, 0] != fa[:, 1]) & (fa[:, 1] != fa[:, 2]) & (fa[:, 0] != fa[:, 2])
    unique &= (fb[:, 0] != fb[:, 1]) & (fb[:, 1] != fb[:, 2]) & (fb[:, 0] != fb[:, 2])
    result[(counts > 0) & (~unique | (counts == 3))] = True
    valid = np.flatnonzero((counts > 0) & ~result)
    if not len(valid):
        return result
    fa, fb, a, b, shared, counts = fa[valid], fb[valid], a[valid], b[valid], shared[valid], counts[valid]
    shared_indices = np.sort(np.where(shared, fa, np.iinfo(np.int64).max), axis=1)
    origin = points[shared_indices[:, 0]]
    allowed0 = np.zeros_like(origin)
    allowed1 = points[np.where(counts == 2, shared_indices[:, 1], shared_indices[:, 0])]-origin
    a, b = a-origin[:, None, :], b-origin[:, None, :]
    na, nb = np.cross(a[:, 1]-a[:, 0], a[:, 2]-a[:, 0]), np.cross(b[:, 1]-b[:, 0], b[:, 2]-b[:, 0])
    la, lb = np.linalg.norm(na, axis=1), np.linalg.norm(nb, axis=1)
    longest_a = np.linalg.norm(np.roll(a, -1, axis=1)-a, axis=2).max(axis=1)
    longest_b = np.linalg.norm(np.roll(b, -1, axis=1)-b, axis=2).max(axis=1)
    degenerate = (la <= tolerance*longest_a) | (lb <= tolerance*longest_b)
    result[valid[degenerate]] = True
    na = na/np.where(la == 0., 1., la)[:, None]
    nb = nb/np.where(lb == 0., 1., lb)[:, None]
    coplanar = (np.abs(np.sum((b-a[:, None, 0, :])*na[:, None, :], axis=2)).max(axis=1) <= tolerance)
    coplanar &= (np.abs(np.sum((a-b[:, None, 0, :])*nb[:, None, :], axis=2)).max(axis=1) <= tolerance)
    for row in np.flatnonzero(coplanar & ~degenerate):
        result[valid[row]] = incident_disallowed_contact(points, fa[row], fb[row], tolerance)
    active = np.flatnonzero(~coplanar & ~degenerate)
    if len(active):
        result[valid[active]] = _batch_noncoplanar(a[active], b[active], na[active], nb[active], allowed0[active], allowed1[active], counts[active], tolerance)
    return result
