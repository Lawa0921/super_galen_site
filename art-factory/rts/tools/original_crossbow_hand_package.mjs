import {spawnSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const run=path.resolve('art-factory/rts/runs/original-crossbow-articulated-hand/2026-10-07-v1');
const result=spawnSync(process.execPath,['art-factory/rts/tools/original_crossbow_carry_package.mjs',run,'crossbow-articulated'],{stdio:'inherit',windowsHide:true});
