const out=path.resolve('tmp/rts/handoff-20261006/review-site/crossbow-articulated');
const metadata=JSON.parse(await readFile(path.join(out,'crossbow-preview.json'),'utf8'));
metadata.crossbow.name='原創弩兵 · 可動手部整合';
