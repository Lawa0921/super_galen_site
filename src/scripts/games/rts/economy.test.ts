import { describe,expect,it } from 'vitest';
import {createState,addBuilding,buildings,units,population,destroyEntity} from './state';
import {issueCommand} from './commands';
import {stepEconomy} from './economy';
import type {RtsMap} from './maps';
const flat=():RtsMap=>({id:'river',name:'Test',width:96,height:96,blocked:new Uint8Array(9216),noBuild:new Uint8Array(9216),spawns:[{x:15.5,z:48.5},{x:80.5,z:48.5}],resources:[{id:'gold',kind:'gold',x:15.5,z:57.5,amount:1000},{id:'wood',kind:'wood',x:25.5,z:57.5,amount:1000}],camps:[]});
const setup=()=>{const s=createState(flat(),1);return {s,h:buildings(s,0)[0],w:units(s,0)[0]};};
const advance=(s:ReturnType<typeof createState>,seconds:number)=>{for(let i=0;i<seconds*20;i++){s.time+=.05;stepEconomy(s,.05);}};
describe('command economy and production',()=>{
  it('charges once, reserves population and finishes a real unit',()=>{const {s,h}=setup();
    expect(issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker',commandId:'a'})).toEqual({ok:true});
    expect(s.teams[0].gold).toBe(450);expect(population(s,0).reserved).toBe(1);
    expect(issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker',commandId:'a'}).ok).toBe(false);
    advance(s,7);expect(population(s,0)).toEqual({used:6,reserved:0,cap:10});expect(s.teams[0].gold).toBe(450);
  });
  it('rejects insufficient funds, opposing ownership and over-cap requests atomically',()=>{const {s,h}=setup();
    s.teams[0].gold=49;expect(issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker'}).ok).toBe(false);expect(h.queue).toHaveLength(0);expect(s.teams[0].gold).toBe(49);
    s.teams[0].gold=1000;expect(issueCommand(s,1,{type:'train',buildingId:h.id,unit:'worker'}).ok).toBe(false);
    for(let i=0;i<5;i++)expect(issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker'}).ok).toBe(true);
    expect(issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker'}).ok).toBe(false);expect(s.teams[0].gold).toBe(750);
  });
  it('fully refunds waiting work and proportionally refunds active work',()=>{const {s,h}=setup();
    issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker'});issueCommand(s,0,{type:'train',buildingId:h.id,unit:'worker'});
    advance(s,3);expect(issueCommand(s,0,{type:'cancel',buildingId:h.id,queueId:h.queue[1].id}).ok).toBe(true);expect(s.teams[0].gold).toBe(450);
    issueCommand(s,0,{type:'cancel',buildingId:h.id});expect(s.teams[0].gold).toBe(475);expect(population(s,0).reserved).toBe(0);
  });
  it.each([[0,80,30],[.25,60,22],[.4,48,18],[.999,0,0]])('refunds paid construction at progress %s once, rounding down each resource',(progress,gold,wood)=>{
    const {s,w}=setup(),opening={gold:s.teams[0].gold,wood:s.teams[0].wood};
    expect(issueCommand(s,0,{type:'build',workerId:w.id,building:'house',position:{x:22.5,z:56.5}}).ok).toBe(true);
    const house=buildings(s,0).find(b=>b.kind==='house')!,helper=units(s,0).find(u=>u.id!==w.id)!;
    const paid={gold:s.teams[0].gold,wood:s.teams[0].wood};
    expect(paid).toEqual({gold:opening.gold-house.spent.gold,wood:opening.wood-house.spent.wood});
    expect(issueCommand(s,0,{type:'resume',unitIds:[helper.id],targetId:house.id}).ok).toBe(true);
    house.construction=progress;
    expect(issueCommand(s,0,{type:'cancel',buildingId:house.id}).ok).toBe(true);
    expect(s.teams[0]).toMatchObject({gold:paid.gold+gold,wood:paid.wood+wood});
    expect(s.economyLog.filter(e=>e.reason==='cancel-construction')).toEqual([{time:s.time,team:0,reason:'cancel-construction',gold,wood}]);
    expect(house).toMatchObject({alive:false,removalReason:'cancelled'});
    // Orders are resolved by the fixed simulation tick; cancelled work must
    // never gain another increment or consume either of its living builders.
    stepEconomy(s,.05);
    for(const worker of [w,helper])expect(worker).toMatchObject({alive:true,order:{type:'idle'}});
    expect(house.construction).toBe(progress);
    expect(s.events.some(e=>e.entityId===house.id&&e.type==='construction-complete')).toBe(false);
    expect(issueCommand(s,0,{type:'cancel',buildingId:house.id}).ok).toBe(false);
    expect(s.teams[0]).toMatchObject({gold:paid.gold+gold,wood:paid.wood+wood});
    expect(s.economyLog.filter(e=>e.reason==='cancel-construction')).toHaveLength(1);
  });
  it('requires actual tier and unique hero, and never applies interrupted research',()=>{const {s}=setup();const b=addBuilding(s,0,'barracks',{x:30,z:20},true);const a=addBuilding(s,0,'altar',{x:38,z:20},true);const f=addBuilding(s,0,'forge',{x:30,z:29},true);
    expect(issueCommand(s,0,{type:'train',buildingId:b.id,unit:'crossbow'}).ok).toBe(false);
    expect(issueCommand(s,0,{type:'train',buildingId:a.id,unit:'commander'}).ok).toBe(true);
    expect(issueCommand(s,0,{type:'train',buildingId:a.id,unit:'commander'}).ok).toBe(false);
    expect(issueCommand(s,0,{type:'research',buildingId:f.id,research:'weapons2'}).ok).toBe(false);
    expect(issueCommand(s,0,{type:'research',buildingId:f.id,research:'weapons1'}).ok).toBe(true);destroyEntity(s,f);advance(s,40);expect(s.teams[0].research).toEqual([]);
  });
  it('collects finite resources into cargo before depositing, then stops at depletion',()=>{const {s,w}=setup();s.resources[0].remaining=10;
    expect(issueCommand(s,0,{type:'gather',unitIds:[w.id],resourceId:'gold'}).ok).toBe(true);
    advance(s,4);expect(s.teams[0].gold).toBe(500);expect(w.cargo.amount).toBeGreaterThan(0);
    advance(s,20);expect(s.teams[0].gold).toBe(510);expect(s.resources[0].remaining).toBe(0);expect(s.teams[0].stats.gatheredGold).toBe(10);
  });
  it('builds with a living worker and resumes the same structure after the builder dies',()=>{const {s,w}=setup();
    expect(issueCommand(s,0,{type:'build',workerId:w.id,building:'house',position:{x:22.5,z:56.5}}).ok).toBe(true);
    const house=buildings(s,0).find(b=>b.kind==='house')!;advance(s,8);expect(house.construction).toBeGreaterThan(0);expect(house.construction).toBeLessThan(1);
    destroyEntity(s,w);const progress=house.construction;advance(s,4);expect(house.construction).toBe(progress);
    expect(issueCommand(s,0,{type:'resume',unitIds:[units(s,0)[0].id],targetId:house.id}).ok).toBe(true);advance(s,20);expect(house.construction).toBe(1);expect(population(s,0).cap).toBe(20);
  });
  it('rejects impassable placement and invalid coordinates without charging',()=>{const {s,w}=setup();s.map.noBuild.fill(1);
    expect(issueCommand(s,0,{type:'build',workerId:w.id,building:'house',position:{x:30,z:30}}).ok).toBe(false);
    expect(issueCommand(s,0,{type:'move',unitIds:[w.id],position:{x:NaN,z:30}}).ok).toBe(false);expect(s.teams[0].gold).toBe(500);
  });
});
